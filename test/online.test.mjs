import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createServer} from 'node:net';
import {once} from 'node:events';
import WebSocket from 'ws';
import {createReview} from '../public/replay.mjs';
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
test('health, origin rejection, private invite, authoritative snapshots and disconnect', {timeout:10000},async t=>{
 const probe=createServer().listen(0,'127.0.0.1');await once(probe,'listening');const port=probe.address().port;await new Promise(r=>probe.close(r));
 const origin='http://127.0.0.1:'+port;
 const child=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:String(port),HOST:'127.0.0.1',PUBLIC_ORIGIN:origin},stdio:'inherit'});
 t.after(()=>child.kill());
 let ready=false;for(let i=0;i<50;i++){try{ready=(await fetch(origin+'/fight/health')).ok;if(ready)break;}catch{}await sleep(50);}assert(ready);
 const bad=new WebSocket(origin.replace('http','ws')+'/fight/socket',{origin:'https://example.invalid'});const [err]=await once(bad,'error');assert.match(err.message,/403/);
 const open=async()=>{
   const c=new WebSocket(origin.replace('http','ws')+'/fight/socket',{origin});t.after(()=>c.terminate());
   const pending=[];c.on('message',x=>pending.push(JSON.parse(x)));
   await once(c,'open');
   return {c,send:m=>c.send(JSON.stringify(m)),get:async pred=>{for(let i=0;i<110;i++){const k=pending.findIndex(pred);if(k>=0)return pending.splice(k,1)[0];await sleep(35);}throw Error('Missing expected server message');}};
 };
 const a=await open();a.send({t:'hello',arena:'cistern'});const room=await a.get(m=>m.t==='room');assert.equal(room.slot,0);assert.equal(room.arena,'cistern');
 const b=await open();b.send({t:'hello',code:room.code});const joined=await b.get(m=>m.t==='room');assert.equal(joined.slot,1);assert.equal(joined.arena,'cistern');
 const full=await open();full.send({t:'hello',code:room.code});assert.match((await full.get(m=>m.t==='error')).message,/full/);
 const denied=await open();denied.send({t:'watch',code:room.code});
 assert.match((await denied.get(m=>m.t==='error')).message,/closed/);
 a.send({t:'gallery',open:true});const gallery=await a.get(m=>m.t==='gallery');assert.notEqual(gallery.code,room.code);
 const spectator=await open();spectator.send({t:'watch',code:gallery.code});await spectator.get(m=>m.t==='watching');
 const watched=await spectator.get(m=>m.t==='state'&&!m.s.ready);assert.equal(watched.ack,undefined);
 spectator.send({t:'input',x:1,y:0,act:'shot',seq:1});
 const unchanged=await spectator.get(m=>m.t==='state'&&m.s.tick>watched.s.tick+12);
 assert.equal(unchanged.s.p[0].x,watched.s.p[0].x);assert.equal(unchanged.s.p[0].ammo,3);
 const state=await a.get(m=>m.t==='state'&&!m.s.ready);
 b.send({t:'input',x:-1,y:0,act:'',seq:1,hp:0});
 const moved=await a.get(m=>m.t==='state'&&m.s.p[1].x<state.s.p[1].x);assert.equal(moved.s.p[1].hp,100);assert.equal(moved.ack,0);
 const confirmed=await b.get(m=>m.t==='state'&&m.ack===1);assert(confirmed.s.p[1].x<state.s.p[1].x);
 b.send({t:'input',x:1,y:0,act:'shot',seq:1});
 const stale=await b.get(m=>m.t==='state'&&m.s.tick>confirmed.s.tick+12);assert.equal(stale.s.p[1].ammo,3);assert.equal(stale.ack,1);
 b.send({t:'input',x:0,y:0,act:'hew',seq:2});
 await b.get(m=>m.t==='state'&&m.s.p[1].act==='hew'&&m.s.p[1].age>=5&&m.s.p[1].age<12);
 b.send({t:'input',x:0,y:0,act:'feint',seq:3});
 const feinted=await b.get(m=>m.t==='state'&&m.ack===3&&m.s.p[1].act==='feint');assert.equal(feinted.s.p[1].st,62);
 b.send({t:'replay'});
 const capture=await b.get(m=>m.t==='replay'), review=createReview(capture);assert.equal(capture.arena,'cistern');
 assert.deepEqual(review.at(feinted.s.tick),feinted.s);
 assert.equal(review.complete,false);
 spectator.send({t:'replay'});spectator.send({t:'ping',id:999});
 assert.equal((await spectator.get(m=>m.t==='replay'||(m.t==='pong'&&m.id===999))).t,'pong');
 a.send({t:'gallery',open:false});assert.equal((await a.get(m=>m.t==='gallery')).code,null);
 assert.match((await spectator.get(m=>m.t==='error')).message,/closed/);
 const revoked=await open();revoked.send({t:'watch',code:gallery.code});
 assert.match((await revoked.get(m=>m.t==='error')).message,/closed/);
 a.send({t:'gallery',open:true});const replacement=await a.get(m=>m.t==='gallery');
 assert.notEqual(replacement.code,gallery.code);
 const remaining=await open();remaining.send({t:'watch',code:replacement.code});await remaining.get(m=>m.t==='watching');
 b.c.close();assert.match((await remaining.get(m=>m.t==='error')).message,/disconnected/);assert.match((await a.get(m=>m.t==='error')).message,/disconnected/);
});
