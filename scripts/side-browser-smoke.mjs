import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {setTimeout as sleep} from 'node:timers/promises';
import {chromium} from 'playwright';
const base='http://127.0.0.1:18872';
const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'18872',HOST:'127.0.0.1',PUBLIC_ORIGIN:base},stdio:'inherit'});
let browser;
const errors=[];
async function until(fn,label){
 for(let i=0;i<150;i++){if(await fn())return;await sleep(50);}
 throw Error('Side-view smoke timed out: '+label);
}
try{
 await until(async()=>{try{return (await fetch(base+'/fight/health')).ok;}catch{return false;}},'server health');
 browser=await chromium.launch();
 const page=await browser.newPage({viewport:{width:1340,height:900},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.url().startsWith(base)&&r.status()>=400)errors.push(r.status()+' '+r.url());});
 await page.goto(base+'/fight/side/');
 assert.match(await page.title(),/Side-View Combat Lab/);
 assert.equal(await page.locator('#frame-table tbody tr').count(),3);
 assert.equal(await page.locator('#stage-select').inputValue(),'reliquary');
 assert.match(await page.locator('#stage-title').textContent(),/ASHEN RELIQUARY/);
 assert.equal(await page.locator('#fight-canvas').getAttribute('data-mode'),'idle');
 assert.match(await page.locator('#live-spacing').textContent(),/Center distance/);
 await page.locator('#opponent').selectOption('dummy');
 await page.locator('#begin').click();
 await until(async()=>Number(await page.locator('#fight-canvas').getAttribute('data-tick'))>100,'round countdown advances');
 const before=Number(await page.locator('#fight-canvas').getAttribute('data-veil-x'));
 await page.keyboard.down('d');await sleep(400);await page.keyboard.up('d');
 await until(async()=>Number(await page.locator('#fight-canvas').getAttribute('data-veil-x'))>before+25,'horizontal movement from KBM');
 await page.keyboard.down('w');await sleep(90);
 const jump=Number(await page.locator('#fight-canvas').getAttribute('data-veil-y'));
 await page.keyboard.up('w');
 assert(jump<436,'rising-edge jump affects vertical world coordinates');
 await sleep(500);
 await page.keyboard.down('s');await sleep(100);
 await page.keyboard.up('s');
 await page.locator('#show-boxes').check();
 assert.match(await page.locator('#live-phase-0').textContent(),/ready|active|recovery|startup|airborne|crouch/i);
 assert.match(await page.locator('#live-performance').textContent(),/frame interval p95/);
 await page.screenshot({path:'artifacts/side-reliquary-characters-and-hitboxes.png'});
 await page.locator('#fight-canvas').screenshot({path:'artifacts/side-reliquary-hitboxes-canvas.png'});
 await page.locator('#show-boxes').uncheck();
 const start=Number(await page.locator('#fight-canvas').getAttribute('data-veil-x'));
 assert(start>200,'current fighter world X is valid');
 await page.keyboard.down('d');
 await until(async()=>Number(await page.locator('#fight-canvas').getAttribute('data-veil-x'))>=610,'close to genuine side-view hitbox range');
 await page.keyboard.up('d');
 await page.keyboard.press('j');await sleep(250);
 assert(Number(await page.locator('#fight-canvas').getAttribute('data-cinder-hp'))<100,'real side-view hitbox attack damages opponent');
 await page.screenshot({path:'artifacts/side-reliquary-duel.png'});
 await page.locator('#fight-canvas').screenshot({path:'artifacts/side-reliquary-canvas.png'});
 assert(await page.locator('#record-save').isEnabled());
 await page.locator('#review').click();
 assert.match(await page.locator('#fight-status').textContent(),/Replay loaded/);
 const range=page.locator('#replay-seek');
 assert(Number(await range.getAttribute('max'))>140);
 await range.evaluate(el=>{el.value='135';el.dispatchEvent(new Event('input',{bubbles:true}));});
 assert.equal(await page.locator('#replay-frame').textContent(), '135 / '+await range.getAttribute('max'));
 await page.locator('#frame-next').click();
 assert.match(await page.locator('#replay-frame').textContent(),/^136 \/ /);
 await page.locator('#takeover').click();
 await until(async()=>await page.locator('#fight-canvas').getAttribute('data-mode')==='takeover','live local replay takeover');
 await page.keyboard.down('ArrowLeft');await sleep(160);await page.keyboard.up('ArrowLeft');
 assert(Number(await page.locator('#fight-canvas').getAttribute('data-tick'))>136);
 await page.locator('#restart').click();
 await page.locator('#stage-select').selectOption('cistern');
 await page.screenshot({path:'artifacts/side-drowned-cloister.png'});
 await page.locator('#stage-select').selectOption('lantern');
 await page.screenshot({path:'artifacts/side-lantern-court.png'});
 await page.locator('#bindings [data-bind=guard]').click();
 await page.keyboard.press('p');
 assert.match(await page.locator('#bindings [data-bind=guard]').textContent(),/Guard · P/);
 await page.reload();
 assert.match(await page.locator('#bindings [data-bind=guard]').textContent(),/Guard · P/);
 const phone=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,hasTouch:true,isMobile:true});
 phone.on('pageerror',e=>errors.push('phone: '+e.message));
 await phone.goto(base+'/fight/side/');
 assert(await phone.locator('#touch').isVisible());
 await phone.locator('#reduce-motion').check();
 await phone.locator('#begin').click();
 await phone.locator('#touch [data-held=right]').tap();
 await phone.screenshot({path:'artifacts/side-mobile-reduced-motion.png'});
 // New 1v1 side-view socket is separate from legacy overhead matchmaking.
 await page.locator('#side-host').click();
 await until(async()=>/^[A-Za-z0-9_-]{12}$/.test(await page.locator('#side-code').inputValue()),'side room created');
 const code=await page.locator('#side-code').inputValue();
 const guest=await browser.newPage({viewport:{width:1140,height:780}});
 guest.on('pageerror',e=>errors.push('side guest: '+e.message));
 await guest.goto(base+'/fight/side/?room='+code);
 await until(async()=>await page.locator('#fight-canvas').getAttribute('data-mode')==='online','host joined real side duel');
 await until(async()=>await guest.locator('#fight-canvas').getAttribute('data-mode')==='online','guest joined real side duel');
 assert.match(await page.locator('#stage-mode').textContent(),/AUTHORITATIVE/);
 assert.equal(await guest.locator('#stage-select').inputValue(),await page.locator('#stage-select').inputValue());
 await until(async()=>Number(await page.locator('#fight-canvas').getAttribute('data-tick'))>108,'server countdown concluded');
 const startX=Number(await page.locator('#fight-canvas').getAttribute('data-veil-x'));
 await page.keyboard.down('d');await sleep(340);await page.keyboard.up('d');
 await until(async()=>Number(await page.locator('#fight-canvas').getAttribute('data-veil-x'))>startX+25,'authoritative server movement');
 await until(async()=>Math.abs(Number(await guest.locator('#fight-canvas').getAttribute('data-veil-x'))-
     Number(await page.locator('#fight-canvas').getAttribute('data-veil-x')))<12,'guest sees same hunter state');
 assert.match(await page.locator('#side-network').textContent(),/input receipt ACK/);
 assert.match(await page.locator('#side-network').textContent(),/RTT median/);
 await page.locator('#fight-canvas').screenshot({path:'artifacts/side-online-authoritative-1v1.png'});
 await guest.close();
 await until(async()=>await page.locator('#fight-canvas').getAttribute('data-mode')==='idle','private opponent disconnect closes match');
 assert.deepEqual(errors,[]);
 console.log('Side-view Chromium: horizontal movement, jump, crouch, combat hitbox, replay seek/takeover, bindings, all stages, mobile touch and reduced effects passed.');
}finally{try{await browser?.close();}finally{server.kill();}}
